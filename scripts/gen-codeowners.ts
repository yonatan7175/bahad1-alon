// Generates .github/CODEOWNERS (plan 08 — Ownership): the owner owns everything;
// each app's authors also own its folders. Run after merging a new app: pnpm codeowners
// `--check` exits 1 when the committed file is out of date.
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import path from "node:path";

const PLACEHOLDER = "REPLACE-ME";

export function codeownersText(): string {
  const cfg = JSON.parse(readFileSync("bahad.config.json", "utf8"));
  const owner: string = cfg.owner;
  if (!owner || owner === PLACEHOLDER) throw new Error("Set the owner first: pnpm set-owner <github-username>");
  const lines = [
    "# GENERATED by scripts/gen-codeowners.ts from bahad.config.json + apps/*/app.json — run: pnpm codeowners",
    `* @${owner}`,
  ];
  for (const slug of readdirSync("apps").sort()) {
    const p = path.join("apps", slug, "app.json");
    if (!existsSync(p)) continue;
    const m = JSON.parse(readFileSync(p, "utf8"));
    const authors = [...new Set([owner, ...(m.authors ?? []).filter((a: string) => a !== PLACEHOLDER)])].map((a) => `@${a}`).join(" ");
    lines.push(`/apps/${slug}/ ${authors}`);
    if (m.tier === "full") lines.push(`/src/app/a/${slug}/ ${authors}`);
  }
  return lines.join("\n") + "\n";
}

export function writeCodeowners() {
  writeFileSync(".github/CODEOWNERS", codeownersText());
  console.log("✔ .github/CODEOWNERS");
}

if (require.main === module) {
  try {
    if (process.argv.includes("--check") && JSON.parse(readFileSync("bahad.config.json", "utf8")).owner === PLACEHOLDER) {
      console.log("ℹ CODEOWNERS check skipped: owner not set yet (pnpm set-owner <github-username>)");
    } else if (process.argv.includes("--check")) {
      const cur = existsSync(".github/CODEOWNERS") ? readFileSync(".github/CODEOWNERS", "utf8") : "";
      if (cur !== codeownersText()) {
        console.error("✖ .github/CODEOWNERS is out of date — run: pnpm codeowners");
        process.exit(1);
      }
      console.log("✔ CODEOWNERS up to date");
    } else writeCodeowners();
  } catch (e) {
    console.error((e as Error).message);
    process.exit(1);
  }
}
