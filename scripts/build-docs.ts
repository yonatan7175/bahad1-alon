// Generates every developer-facing doc from ONE source (plan 09 — Single source of truth):
//   docs/platform/*.md + src/platform/types.ts + manifest schema + tags + limits
//     → src/generated/docs.ts (the /dev pages)
//     → public/llms.txt, public/llms-full.txt, public/bahad.d.ts
// `--check` fails when CLAUDE.md's rules block is out of sync; `--sync-claude` rewrites it.
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { marked } from "marked";
import { manifestJsonSchema, MAX_RECORDS_PER_USER, tagsFileSchema } from "../src/platform/manifest";
import { LIMITS } from "../src/platform/limits";

const ROOT = path.resolve(__dirname, "..");
const DOCS = path.join(ROOT, "docs", "platform");
const RULES_RE = /<!-- RULES-START[^>]*-->([\s\S]*?)<!-- RULES-END -->/;

export interface DocPage {
  slug: string; // "" = /dev
  title: string;
  markdown: string;
  html: string;
}

export async function apiTypesText(): Promise<string> {
  const src = await readFile(path.join(ROOT, "src/platform/types.ts"), "utf8");
  return src
    .replace(/^\/\/.*\n/gm, "")
    .replace(/^export (type|interface) /gm, "$1 ")
    .trim();
}

export async function bahadDts(): Promise<string> {
  return (
    "// bahad.d.ts — TypeScript types for the Alon battalion portal Platform API (v1).\n" +
    "// Generated from src/platform/types.ts. Use: /// <reference path=\"bahad.d.ts\" />\n\n" +
    (await apiTypesText()) +
    "\n\ndeclare const bahad: Bahad;\ninterface Window {\n  bahad: Bahad;\n}\n"
  );
}

export async function buildDocs(): Promise<DocPage[]> {
  const tags = tagsFileSchema.parse(JSON.parse(await readFile(path.join(ROOT, "apps/tags.json"), "utf8"))).tags;
  const vars: Record<string, string> = {
    SCHEMA: JSON.stringify(manifestJsonSchema(), null, 2),
    TAGS: tags.map((t) => JSON.stringify(t)).join(", "),
    API_TYPES: await apiTypesText(),
    MAX_PER_USER: String(MAX_RECORDS_PER_USER),
    RECORD_KB: String(LIMITS.recordBytes / 1024),
    WRITES_PER_MIN: String(LIMITS.writesPerMinute),
    LIST_DEFAULT: String(LIMITS.listDefault),
    LIST_MAX: String(LIMITS.listMax),
    WHERE_KEYS: String(LIMITS.whereKeys),
    PUSH_DAYS: String(LIMITS.pushMaxAheadDays),
    PUSH_TITLE: String(LIMITS.pushTitle),
    PUSH_BODY: String(LIMITS.pushBody),
    PUSH_PER_DAY: String(LIMITS.pushPerDay),
  };
  const expand = (md: string, file: string) =>
    md.replace(/\{\{([A-Z_]+)\}\}/g, (_, k: string) => {
      if (!(k in vars)) throw new Error(`${file}: unknown placeholder {{${k}}}`);
      return vars[k];
    });

  const files = (await readdir(DOCS)).filter((f) => /^\d\d-.+\.md$/.test(f)).sort();
  const raw = new Map<string, string>();
  for (const f of files) raw.set(f, await readFile(path.join(DOCS, f), "utf8"));
  const apiFile = files.find((f) => f.endsWith("-api.md"));
  if (!apiFile) throw new Error("docs/platform: missing the *-api.md page");
  // The starter prompt embeds the whole API page (expanded).
  vars.API_REFERENCE = expand(raw.get(apiFile)!, apiFile).replace(/^# .*\n/, "").trim();

  const pages: DocPage[] = files.map((f, i) => {
    const markdown = expand(raw.get(f)!, f);
    const title = /^# (.+)$/m.exec(markdown)?.[1]?.trim();
    if (!title) throw new Error(`${f}: first line must be "# Title"`);
    const slug = i === 0 ? "" : f.replace(/^\d\d-/, "").replace(/\.md$/, "");
    const html = (marked.parse(markdown.replace(/<!-- RULES-(START|END)[^>]*-->/g, ""), { async: false, gfm: true }) as string)
      // Every code block gets a copy button (wired by src/app/dev/copy-buttons.tsx).
      .replace(/<pre>/g, '<div class="code-wrap"><button type="button" class="btn-secondary copy-btn">העתקה</button><pre>')
      .replace(/<\/pre>/g, "</pre></div>");
    return { slug, title, markdown, html };
  });

  await mkdir(path.join(ROOT, "src/generated"), { recursive: true });
  await writeFile(
    path.join(ROOT, "src/generated/docs.ts"),
    "// GENERATED by scripts/build-docs.ts from docs/platform/*.md — do not edit.\n" +
      `export interface DocPage { slug: string; title: string; markdown: string; html: string }\n` +
      `export const DOCS: DocPage[] = ${JSON.stringify(pages, null, 2)};\n`,
  );

  const site = (process.env.NEXT_PUBLIC_SITE_URL ?? "").replace(/\/$/, "");
  const link = (p: string) => `${site}${p}`;
  const llms =
    "# Alon battalion portal (אתר הבית — גדוד אלון) — developer docs\n\n" +
    "> How to build an app that plugs into the portal: a simple app (HTML + /bahad.js, sandboxed iframe) or a full app (Next.js + TypeScript), " +
    "using one Platform API for the signed-in user, per-app data storage with access rules, live change signals and push notifications. Hebrew RTL, mobile-first.\n\n" +
    "## Docs\n\n" +
    pages.map((p) => `- [${p.title}](${link(p.slug ? `/dev/${p.slug}` : "/dev")})`).join("\n") +
    "\n\n## Machine-readable\n\n" +
    `- [All docs in one file](${link("/llms-full.txt")}): paste into an AI tool\n` +
    `- [TypeScript types](${link("/bahad.d.ts")}): exact API types\n` +
    `- [Client helper](${link("/bahad.js")}): the script simple apps load\n`;
  await writeFile(path.join(ROOT, "public/llms.txt"), llms);
  await writeFile(
    path.join(ROOT, "public/llms-full.txt"),
    "# Alon battalion portal — complete developer documentation\n\n" + pages.map((p) => p.markdown.replace(/<!-- RULES-(START|END)[^>]*-->\n?/g, "")).join("\n\n---\n\n"),
  );
  await writeFile(path.join(ROOT, "public/bahad.d.ts"), await bahadDts());
  console.log(`[docs] ✔ ${pages.length} pages, llms.txt, llms-full.txt, bahad.d.ts`);
  return pages;
}

/** The rules block from docs/platform/06-rules.md, as it must appear in CLAUDE.md. */
export async function rulesBlock(): Promise<string> {
  const files = (await readdir(DOCS)).filter((f) => f.endsWith("-rules.md"));
  const md = await readFile(path.join(DOCS, files[0]), "utf8");
  const m = RULES_RE.exec(md);
  if (!m) throw new Error("rules page has no RULES-START/RULES-END block");
  return m[1].trim();
}

export async function checkClaudeMd(fix: boolean): Promise<boolean> {
  const file = path.join(ROOT, "CLAUDE.md");
  const text = await readFile(file, "utf8");
  const block = await rulesBlock();
  const m = RULES_RE.exec(text);
  if (!m) throw new Error("CLAUDE.md has no <!-- RULES-START --> … <!-- RULES-END --> block");
  if (m[1].trim() === block) return true;
  if (!fix) return false;
  await writeFile(file, text.replace(RULES_RE, `<!-- RULES-START (generated from docs/platform/06-rules.md — edit there, then run pnpm docs:sync) -->\n${block}\n<!-- RULES-END -->`));
  console.log("[docs] ✔ CLAUDE.md rules block updated");
  return true;
}

if (require.main === module) {
  (async () => {
    await buildDocs();
    if (process.argv.includes("--sync-claude")) await checkClaudeMd(true);
    if (process.argv.includes("--check") && !(await checkClaudeMd(false))) {
      console.error("[docs] ✖ CLAUDE.md rules block is out of sync with docs/platform/06-rules.md — run: pnpm docs:sync");
      process.exit(1);
    }
  })().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
